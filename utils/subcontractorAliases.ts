/**
 * ชื่อผู้รับเหมาที่สะกดต่างกันแต่เป็นเจ้าเดียวกัน
 *
 * ทะเบียนผู้รับเหมามีแค่ 1 รายจาก 36 ชื่อที่ใช้จริง ทุกหน้าจึงให้พิมพ์ชื่อเอง
 * ผลคือเจ้าเดียวกันถูกบันทึกหลายสะกด แล้วระบบมองเป็นคนละบริษัท — รายงานแยกยอด
 * วางบิลรวมไม่ได้ และตารางเรทจับคู่กับราคากลางไม่ติด
 *
 * ไฟล์นี้เป็น "ที่เดียว" ที่บอกว่าชื่อไหนคือเจ้าเดียวกัน ใช้ทั้งตอนนำเข้าไฟล์เรท
 * และตอนเทียบรุ่น เพื่อให้ไฟล์ที่หน่วยงานส่งมาด้วยชื่อเดิมยังจับคู่กับข้อมูล
 * ในระบบได้ โดยไม่ต้องขอให้หน่วยงานแก้ไฟล์
 *
 * เพิ่มชื่อใหม่ที่นี่ที่เดียว — อย่ากระจายการแปลงชื่อไปตามหน้าจอ
 */

/** ชื่อที่สะกดต่าง -> ชื่อมาตรฐาน */
const ALIASES: Record<string, string> = {
    // รถร่วมคุณวสรรณ์ — หน่วยงานเขียน "รถร่วมคุณหนึ่ง" ในไฟล์เรทตามราคาน้ำมัน
    // ผู้ใช้ยืนยันว่าเป็นเจ้าเดียวกัน และเป็นเจ้าเดียวที่ใช้เรทตามน้ำมันตอนนี้
    'รถร่วมคุณหนึ่ง': 'รถร่วมคุณวสรรณ์',
    'รถร่วมวสรรณ์': 'รถร่วมคุณวสรรณ์',
    'รถร่วมนายวสรรณ์': 'รถร่วมคุณวสรรณ์',

    // พิมพ์ตก "ส์" — เส้นทางเดียวกัน รถแบบเดียวกัน ราคาเท่ากันเป๊ะ (18,500)
    'วิวัฒน์ทราน': 'วิวัฒน์ทรานส์',
};

/**
 * ปรับข้อความให้เทียบกันได้ — ตัดช่องว่างหัวท้ายและยุบช่องว่างซ้ำ
 * ไม่แปลงเป็นตัวพิมพ์เล็ก เพราะชื่อไทยไม่มีตัวพิมพ์ใหญ่เล็ก และชื่อย่อภาษาอังกฤษ
 * (KNN, YSK, PTK) ควรคงรูปเดิมไว้เมื่อคืนค่ากลับ
 */
const normalize = (name: string): string => (name || '').trim().replace(/\s+/g, ' ');

/**
 * แปลงชื่อผู้รับเหมาเป็นชื่อมาตรฐาน
 *
 * ชื่อที่ไม่อยู่ในรายการจะถูกคืนกลับตามเดิม (แค่ตัดช่องว่างส่วนเกิน) —
 * ไม่เดาว่าชื่อคล้ายกันคือเจ้าเดียวกัน เพราะเคยพบกรณีที่ชื่อคล้ายแต่คนละเจ้าจริง
 * ("PTK" กับ "พีทีเคทรานสปอร์ต(พี่อ้อย)" เส้นทางไม่ทับกันเลยสักเส้น)
 */
export const canonicalSubcontractor = (name: string): string => {
    const clean = normalize(name);
    return ALIASES[clean] ?? clean;
};

/** ชื่อสองชื่อนี้หมายถึงเจ้าเดียวกันไหม */
export const isSameSubcontractor = (a: string, b: string): boolean =>
    canonicalSubcontractor(a) === canonicalSubcontractor(b);

/** ชื่อพ้องทั้งหมดของชื่อมาตรฐานหนึ่ง — ใช้ค้นหาข้อมูลเก่าที่ยังใช้ชื่อเดิม */
export const aliasesOf = (canonical: string): string[] => {
    const target = canonicalSubcontractor(canonical);
    return Object.entries(ALIASES)
        .filter(([, to]) => to === target)
        .map(([from]) => from);
};
