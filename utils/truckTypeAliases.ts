/**
 * ประเภทรถที่หน่วยงานเขียนยาวกว่าที่ระบบใช้
 *
 * ไฟล์เรทจากหน่วยงานเขียนพิกัดน้ำหนักต่อท้ายชื่อรถ เช่น
 *   "4w (บรรทุกไม่เกิน 3000 กก.)"   ระบบใช้ "4w"
 *   "4wj (บรรทุก 3001 - 3500 กก.)"  ระบบใช้ "4wj"
 *
 * ทุกหน้าจับคู่ใบงานกับราคาด้วยประเภทรถแบบตรงตัว ถ้าไม่ปรับให้ตรงกัน เรทของ
 * หน่วยงานจะไม่มีวันจับคู่กับใบงานได้เลยแม้แต่แถวเดียว โดยไม่มี error ให้เห็น
 *
 * ปรับตอนอ่าน ไม่แก้ข้อมูลที่บันทึกไว้ — ข้อมูลในตารางเรทต้องตรงกับไฟล์ต้นฉบับ
 * เสมอเพื่อให้ตรวจย้อนได้ และไฟล์รอบหน้าที่ยังเขียนแบบเดิมจะจับคู่ได้เอง
 *
 * สำคัญ: ตัดเฉพาะคำอธิบายในวงเล็บ ไม่ยุบประเภทรถเข้าหากัน
 * "4wj" ต้องไม่กลายเป็น "4w" เพราะเป็นคนละพิกัดน้ำหนักและคนละราคา
 * (ระบบมี 4w และ 4wj เป็นคนละตัวเลือกอยู่แล้วใน constants.ts)
 */

/** พิกัดน้ำหนักที่หน่วยงานเขียนไว้ — เก็บไว้แสดงเป็นหมายเหตุ ไม่ทิ้ง */
export const truckTypeSpec = (raw: string): string => {
    const m = (raw || '').match(/\(([^)]*)\)/);
    return m ? m[1].trim() : '';
};

/**
 * ชื่อประเภทรถที่ระบบใช้จับคู่ — ตัดคำอธิบายในวงเล็บออก
 *
 * ชื่อที่ไม่มีวงเล็บคืนกลับตามเดิม (แค่ตัดช่องว่างส่วนเกิน) — ไม่เดาว่าชื่อ
 * ที่สะกดต่างกันคือรถแบบเดียวกัน
 */
export const canonicalTruckType = (raw: string): string =>
    (raw || '').replace(/\([^)]*\)/g, '').trim().replace(/\s+/g, ' ');

/** ประเภทรถสองชื่อนี้หมายถึงรถแบบเดียวกันไหม */
export const isSameTruckType = (a: string, b: string): boolean =>
    canonicalTruckType(a) === canonicalTruckType(b);
