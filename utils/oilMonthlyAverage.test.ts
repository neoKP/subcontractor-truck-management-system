import { describe, it, expect } from 'vitest';
import { monthlyAverageDiesel, monthDaysOf } from './oilMonthlyAverage';
import { OIL_BASE } from './oilRounds';

/*
  ค่าเฉลี่ยราคาน้ำมันรายเดือน — กติกาที่หน่วยงานกำหนด

    เฉลี่ยทั้งเดือนปฏิทิน นับทุกวันเท่ากัน (ส.ค. = 1-31)
    ปัดทศนิยม 3 ตำแหน่ง
    ใช้กับทุกเจ้า ไม่แยกรายเจ้า

  ห้ามเดาค่าให้เดือนที่ข้อมูลไม่ครบ — คิดเงินจากค่าที่เดามาแล้วผิด
  แย่กว่าบอกตรง ๆ ว่ายังคำนวณไม่ได้
*/

/** แปลงราคาดีเซลเป็น %สะสม แบบที่ระบบเก็บจริง */
const pct = (diesel: number): number => Math.round((diesel - OIL_BASE) * 1e6) / 1e6;

describe('monthDaysOf — วันทั้งหมดของเดือน', () => {
    it('นับวันตามปฏิทินจริง ไม่ใช่ 30 วันตายตัว', () => {
        expect(monthDaysOf('2026-08')).toHaveLength(31);
        expect(monthDaysOf('2026-04')).toHaveLength(30);
        expect(monthDaysOf('2026-02')).toHaveLength(28);
    });

    it('รู้จักปีอธิกสุรทิน', () => {
        // 2024 หาร 4 ลงตัว = อธิกสุรทิน · 2026 ไม่ใช่
        expect(monthDaysOf('2024-02')).toHaveLength(29);
        expect(monthDaysOf('2026-02')).toHaveLength(28);
    });

    it('คืนวันแรกและวันสุดท้ายถูกต้อง', () => {
        const days = monthDaysOf('2026-08');
        expect(days[0]).toBe('2026-08-01');
        expect(days[days.length - 1]).toBe('2026-08-31');
    });
});

describe('monthlyAverageDiesel — ค่าเฉลี่ยทั้งเดือน', () => {
    it('ราคาคงที่ทั้งเดือน ค่าเฉลี่ยเท่ากับราคานั้น', () => {
        const r = monthlyAverageDiesel({ '2026-07-01': pct(38.00) }, '2026-08');

        expect(r.usable).toBe(true);
        expect(r.diesel).toBe(38);
        expect(r.days).toBe(31);
    });

    it('ถ่วงตามจำนวนวันที่ราคานั้นใช้อยู่จริง ไม่ใช่เฉลี่ยตามจำนวนงวด', () => {
        /*
          ราคา 30 บาทใช้ 30 วัน (1-30 เม.ย.) แล้วเปลี่ยนเป็น 60 บาทวันสุดท้ายวันเดียว
          ถ้าเฉลี่ยตามงวดจะได้ 45 ซึ่งผิดมหันต์ · ต้องได้ (30x29 + 60x1) / 30
        */
        const r = monthlyAverageDiesel(
            { '2026-03-01': pct(30), '2026-04-30': pct(60) },
            '2026-04'
        );

        expect(r.days).toBe(30);
        expect(r.diesel).toBe(31);   // (30*29 + 60) / 30 = 31
    });

    it('ปัดทศนิยม 3 ตำแหน่งตามที่หน่วยงานกำหนด', () => {
        // 1 วันเป็น 38.00 อีก 30 วันเป็น 37.00 -> 37.032258... -> 37.032
        const r = monthlyAverageDiesel(
            { '2026-07-01': pct(38), '2026-08-02': pct(37) },
            '2026-08'
        );

        expect(r.diesel).toBe(37.032);
    });

    it('ปัดครึ่งขึ้น ไม่ใช่ปัดลง', () => {
        // 14 วันแรก 38.00 + 14 วันหลัง 37.00 ของ ก.พ. (28 วัน) = 37.5 พอดี
        // ต้องไม่ถูกตัดทิ้งเป็น 37
        const r = monthlyAverageDiesel(
            { '2026-01-01': pct(38), '2026-02-15': pct(37) },
            '2026-02'
        );

        expect(r.diesel).toBe(37.5);
    });

    it('ใช้ราคาของงวดล่าสุดที่เริ่มก่อนวันนั้น ไม่ใช่งวดที่ตรงวันเป๊ะ', () => {
        /*
          ระบบเก็บเฉพาะ "วันแรกที่ราคามีผล" ไม่ได้เก็บทุกวัน
          ราคาของวันที่ 2-9 ส.ค. จึงเป็นของงวดที่เริ่ม 1 ส.ค. ไม่ใช่ไม่มีข้อมูล
        */
        const r = monthlyAverageDiesel(
            { '2026-08-01': pct(40), '2026-08-11': pct(50) },
            '2026-08'
        );

        // 10 วันแรก 40 บาท (1-10) + 21 วันหลัง 50 บาท (11-31)
        // เขียนค่าที่คาดไว้เป็นตัวเลขตรง ๆ ไม่ใช่สูตรเดียวกับในโค้ด
        // ไม่งั้นถ้าโค้ดปัดผิดวิธี เทสต์จะปัดผิดตามแล้วผ่านไปด้วยกัน
        expect(r.usable).toBe(true);
        expect(r.diesel).toBe(46.774);
        expect(r.days).toBe(31);
    });

    /*
      เดือนที่ข้อมูลไม่ครบ ต้องบอกว่าใช้ไม่ได้ — ห้ามเฉลี่ยเท่าที่มี

      ถ้าเฉลี่ยจากวันที่มีอยู่ ตัวเลขจะดูสมเหตุสมผลแต่ผิด และไม่มีใครรู้ว่าผิด
      เช่นเดือนที่มีข้อมูลแค่ 7 วันแรกซึ่งน้ำมันถูกผิดปกติ จะได้ค่าเฉลี่ยต่ำเกินจริง
    */
    it('เดือนที่ข้อมูลเริ่มกลางเดือนนั้นเอง ต้องบอกว่าใช้ไม่ได้', () => {
        // ข้อมูลเริ่ม 10 ส.ค. แต่ขอเฉลี่ยเดือน ส.ค. — วันที่ 1-9 ไม่มีราคา
        const r = monthlyAverageDiesel({ '2026-08-10': pct(40) }, '2026-08', '2026-09-05');

        expect(r.usable).toBe(false);
        expect(r.status).toBe('before-history');
        expect(r.diesel).toBe(0);
    });

    it('เดือนที่ข้อมูลเริ่มหลังเดือนนั้นทั้งเดือน ก็ใช้ไม่ได้', () => {
        const r = monthlyAverageDiesel({ '2026-08-10': pct(40) }, '2026-07', '2026-09-05');

        expect(r.usable).toBe(false);
        expect(r.status).toBe('before-history');
    });

    it('ข้อมูลเริ่มวันที่ 1 พอดี ใช้ได้', () => {
        const r = monthlyAverageDiesel({ '2026-08-01': pct(40) }, '2026-08', '2026-09-05');

        expect(r.usable).toBe(true);
        expect(r.diesel).toBe(40);
    });

    it('เดือนอนาคตที่ยังไม่จบ ต้องบอกว่ายังคำนวณไม่ได้', () => {
        // ทาง ก. ที่ตกลงกันไว้: รอสิ้นเดือน ไม่ใช้ค่าชั่วคราวแล้วปรับย้อนหลัง
        const r = monthlyAverageDiesel({ '2026-01-01': pct(38) }, '2026-08', '2026-08-15');

        expect(r.usable).toBe(false);
        expect(r.status).toBe('month-not-over');
    });

    it('เดือนที่เพิ่งจบเมื่อวาน คำนวณได้แล้ว', () => {
        const r = monthlyAverageDiesel({ '2026-01-01': pct(38) }, '2026-08', '2026-09-01');

        expect(r.usable).toBe(true);
        expect(r.diesel).toBe(38);
    });

    it('วันสุดท้ายของเดือนยังไม่ถือว่าจบ', () => {
        // 31 ส.ค. ยังอยู่ในเดือน ราคาวันนั้นยังเปลี่ยนได้
        const r = monthlyAverageDiesel({ '2026-01-01': pct(38) }, '2026-08', '2026-08-31');

        expect(r.usable).toBe(false);
        expect(r.status).toBe('month-not-over');
    });

    it('ไม่มีข้อมูลราคาเลย ต้องบอกว่าใช้ไม่ได้', () => {
        const r = monthlyAverageDiesel({}, '2026-08');

        expect(r.usable).toBe(false);
        expect(r.status).toBe('no-data');
        expect(r.diesel).toBe(0);
    });

    it('รับเดือนผิดรูปแบบได้โดยไม่พัง', () => {
        expect(monthlyAverageDiesel({ '2026-01-01': pct(38) }, 'สิงหาคม').usable).toBe(false);
        expect(monthlyAverageDiesel({ '2026-01-01': pct(38) }, '').usable).toBe(false);
        expect(monthlyAverageDiesel({ '2026-01-01': pct(38) }, '2026-13').usable).toBe(false);
    });

    it('บอกช่วงราคาต่ำสุด-สูงสุดของเดือน เพื่อให้เห็นว่าผันผวนแค่ไหน', () => {
        const r = monthlyAverageDiesel(
            { '2026-03-01': pct(30), '2026-04-15': pct(50) },
            '2026-04'
        );

        expect(r.min).toBe(30);
        expect(r.max).toBe(50);
    });

    /*
      ผู้เรียกอาจส่ง today เป็น timestamp เต็ม

      โค้ดในระบบนี้ใช้ new Date().toISOString() อยู่หลายสิบที่ ซึ่งได้
      "2026-08-31T10:30:00Z" · สตริงนั้น "มากกว่า" 2026-08-31 เพราะ T เรียงหลัง
      ถ้าเทียบดิบ ๆ ด่านกันเดือนยังไม่จบจะหลุดพอดีในวันสุดท้ายของเดือน
      ซึ่งเป็นวันที่คนปิดยอดมีโอกาสกดมากที่สุด
    */
    it('today ที่เป็น timestamp เต็ม ต้องได้ผลเหมือนวันที่ล้วน', () => {
        const bands = { '2026-01-01': pct(38) };

        expect(monthlyAverageDiesel(bands, '2026-08', '2026-08-31T10:30:00Z').status)
            .toBe('month-not-over');
        expect(monthlyAverageDiesel(bands, '2026-08', '2026-09-01T00:00:00Z').usable)
            .toBe(true);
    });

    it('เดือนที่ยังไม่เริ่มด้วยซ้ำ ต้องไม่คืนค่า', () => {
        // ขอเดือน ส.ค. ตั้งแต่เดือน มี.ค. — ห้ามเอาราคาเดือน มี.ค. ไปยืดคลุมทั้งเดือน ส.ค.
        const r = monthlyAverageDiesel({ '2026-01-01': pct(38) }, '2026-08', '2026-03-01');

        expect(r.usable).toBe(false);
        expect(r.status).toBe('month-not-over');
    });

    /*
      ค่าที่ไม่ใช่ตัวเลขใช้ได้จริง ต้องไม่คืนค่าที่ "ดูใช้ได้"

      RTDB เก็บคีย์ที่ถูกลบเป็น null · ถ้าปล่อยผ่านจะกลายเป็น 0 แล้วราคาเหลือ
      แค่ OIL_BASE 31.94 เงียบ ๆ ทั้งที่จริงคือ 40 บาท — ผิดไป 8 บาท/ลิตร
      โดยไม่มีอะไรบอก · ส่วน NaN ทำให้คิดเงินจาก NaN ได้เลยถ้าเช็คแค่ usable
    */
    it('ค่าที่ไม่ใช่ตัวเลขใช้ได้จริง ต้องบอกว่าใช้ไม่ได้ ไม่ใช่คืนค่ามั่ว', () => {
        const bad = [NaN, undefined, null, Infinity, -Infinity, 'สี่สิบ'];

        for (const v of bad) {
            const r = monthlyAverageDiesel(
                { '2026-07-01': pct(40), '2026-08-15': v as unknown as number },
                '2026-08',
                '2026-09-05'
            );

            expect(r.usable, String(v)).toBe(false);
            // แยกจาก no-data — มีข้อมูลแต่เสีย ต้องไปไล่ดูที่ต้นทาง คนละทางแก้กัน
            expect(r.status, String(v)).toBe('bad-data');
        }
    });

    it('ค่าเสียในงวดที่ไม่เกี่ยวกับเดือนนี้ ต้องไม่ทำให้คำนวณไม่ได้', () => {
        /*
          ประวัติราคาเก็บยาวหลายปี ถ้าคีย์เสียตัวเดียวทำให้ทุกเดือนพัง
          ระบบจะใช้ไม่ได้ทั้งระบบเพราะข้อมูลปีก่อนมีปัญหา ซึ่งไม่สมเหตุสมผล
        */
        const r = monthlyAverageDiesel(
            { '2026-07-01': pct(40), '2026-12-25': null as unknown as number },
            '2026-08',
            '2026-09-05'
        );

        expect(r.usable).toBe(true);
        expect(r.diesel).toBe(40);
    });

    it('ปัดครึ่งขึ้นได้จริงแม้ค่าลงตัวพอดีที่ตำแหน่งที่ 4', () => {
        /*
          7 วัน 35.00 + 21 วัน 35.01 ของ ก.พ. = 35.0075 พอดี
          ถ้าบวกทศนิยมสะสมแล้วค่อยปัด จะได้ 35.007 เพราะ float ต่ำกว่าจุดครึ่งนิดเดียว
          หน่วยงานคำนวณด้วยมือจะได้ 35.008
        */
        const r = monthlyAverageDiesel(
            { '2026-01-01': pct(35.00), '2026-02-08': pct(35.01) },
            '2026-02',
            '2026-03-01'
        );

        expect(r.diesel).toBe(35.008);
    });

    it('วันที่ที่รูปแบบถูกแต่ไม่มีอยู่จริง ต้องถูกทิ้ง', () => {
        /*
          2026-02-31 ไม่มีอยู่จริง แต่ผ่าน regex รูปแบบวันที่ได้
          ถ้าไม่ทิ้ง มันจะเรียงต่อจาก 2026-02-28 แล้วถูกใช้เป็นราคาของวันสุดท้าย
          ทำให้ค่าเฉลี่ยเพี้ยนโดยไม่มีอะไรบอก

          2026-08-00 กับ 2026-13-01 ถูก regex ปัดตกไปตั้งแต่แรกอยู่แล้ว
        */
        // 2026-04-31 ไม่มีอยู่จริง (เม.ย. มี 30 วัน) แต่เรียง "ก่อน" เดือน พ.ค.
        // ถ้าไม่ทิ้ง มันจะกลายเป็นงวดล่าสุดก่อนเดือน พ.ค. = ราคาของทั้งเดือน
        const r = monthlyAverageDiesel(
            { '2026-01-01': pct(40), '2026-04-31': pct(99) },
            '2026-05',
            '2026-06-05'
        );

        expect(r.diesel).toBe(40);

        // วันที่รูปแบบผิดชัดเจนก็ต้องถูกทิ้งเช่นกัน
        const r2 = monthlyAverageDiesel(
            { '2026-08-00': pct(99), '2026-07-01': pct(40) },
            '2026-08',
            '2026-09-05'
        );

        expect(r2.diesel).toBe(40);

        /*
          เดือนที่เกินช่วง ต้องพึ่ง regex เท่านั้น การตรวจปฏิทินกันไม่ได้

          new Date(Date.UTC(2026, 12, 1)) ทดไปเป็น 2027-01-01 แล้ว getUTCDate()
          คืน 1 ซึ่งตรงกับเลขวันที่เขียนไว้พอดี จึงผ่านการตรวจปฏิทินไปได้
          ส่วน 2026-00-15 ทดถอยหลังไปเป็น 2025-12-15 ก็ได้ 15 ตรงกันเช่นกัน
          และมันเรียงก่อนงวดจริง จึงกลายเป็นราคาของทั้งเดือน
        */
        // ต้องไม่มีงวดจริงคั่นกลาง ไม่งั้นงวดจริงจะทับค่าเสียไปเองโดยบังเอิญ
        // แล้วเทสต์จะผ่านทั้งที่ระบบไม่ได้กันอะไรเลย
        const r3 = monthlyAverageDiesel(
            { '2025-01-01': pct(40), '2026-00-15': pct(88) },
            '2026-08',
            '2026-09-05'
        );

        expect(r3.diesel).toBe(40);
    });

});
