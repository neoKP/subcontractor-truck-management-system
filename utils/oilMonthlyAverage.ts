import { OIL_BASE, type OilBands } from './oilRounds';

/**
 * ค่าเฉลี่ยราคาดีเซลรายเดือน — ตามกติกาที่หน่วยงานอัตราจ้างกำหนด
 *
 * กติกา (ยืนยันกับหน่วยงานแล้ว)
 *   เฉลี่ยทั้งเดือนปฏิทิน นับทุกวันเท่ากัน · ส.ค. คือวันที่ 1-31
 *   ปัดทศนิยม 3 ตำแหน่ง
 *   ใช้กับทุกเจ้าเหมือนกันหมด ไม่แยกรายเจ้า
 *
 * ไฟล์นี้ "คำนวณอย่างเดียว" ยังไม่ได้ถูกเอาไปใช้คิดเงินจริง — ระบบยังคิดจาก
 * ราคาของวันที่ต้องการรถอยู่ (ดู oilPriceAtDate) · มีไว้ให้เทียบตัวเลขก่อน
 * ตัดสินใจเปลี่ยนวิธีคิด เพราะผลต่างเป็นเงินจริงหลักร้อยบาทต่อเที่ยว
 */

export type MonthAvgStatus =
    /** คำนวณได้ ใช้คิดเงินได้ */
    | 'exact'
    /** เดือนยังไม่จบ — ค่าเฉลี่ยยังเปลี่ยนได้ ต้องรอสิ้นเดือน */
    | 'month-not-over'
    /** ข้อมูลราคาเริ่มหลังเดือนนี้ — ไม่รู้ราคาจริง ต้องไม่เดา */
    | 'before-history'
    /** ไม่มีข้อมูลราคาเลย หรือรูปแบบเดือนไม่ถูกต้อง */
    | 'no-data'
    /**
     * มีข้อมูลแต่ใช้ไม่ได้ — เจอค่าที่ไม่ใช่ตัวเลข (null/NaN) ในงวดที่เกี่ยวข้อง
     *
     * แยกจาก no-data เพราะคนละสาเหตุและคนละทางแก้: no-data คือยังไม่มีข้อมูล
     * ส่วนนี่คือข้อมูลเสีย ต้องไปไล่ดูที่ต้นทาง · ถ้ารวมเป็นสถานะเดียว
     * คนที่มาดูว่าทำไมเดือนนี้คำนวณไม่ได้จะแยกไม่ออกว่าต้องแก้ตรงไหน
     */
    | 'bad-data';

export interface MonthlyAverage {
    /** ค่าเฉลี่ยราคาดีเซล ปัด 3 ตำแหน่ง — 0 เมื่อคำนวณไม่ได้ */
    diesel: number;
    /** เดือนที่คำนวณ รูปแบบ YYYY-MM */
    month: string;
    /** จำนวนวันที่นำมาเฉลี่ย — 0 เมื่อคำนวณไม่ได้ */
    days: number;
    /** ราคาต่ำสุดที่พบในเดือน — ใช้ดูว่าเดือนนั้นผันผวนแค่ไหน */
    min: number;
    /** ราคาสูงสุดที่พบในเดือน */
    max: number;
    status: MonthAvgStatus;
    /** ใช้คิดเงินได้ไหม */
    usable: boolean;
}

const EMPTY: Omit<MonthlyAverage, 'month'> = {
    diesel: 0, days: 0, min: 0, max: 0, status: 'no-data', usable: false,
};

/** ตรวจว่าเป็นรูปแบบ YYYY-MM ที่เดือนอยู่ในช่วง 01-12 */
const validMonth = (m: string): boolean => /^\d{4}-(0[1-9]|1[0-2])$/.test(m || '');

/**
 * รายการวันทั้งหมดของเดือน (ISO) เรียงจากน้อยไปมาก
 *
 * ใช้ Date ของ JS หาจำนวนวันแทนตารางตายตัว เพื่อให้ปีอธิกสุรทินถูกเสมอ
 * (วันที่ 0 ของเดือนถัดไป = วันสุดท้ายของเดือนนี้)
 */
export function monthDaysOf(month: string): string[] {
    if (!validMonth(month)) return [];
    const [y, m] = month.split('-').map(Number);
    const count = new Date(Date.UTC(y, m, 0)).getUTCDate();
    return Array.from(
        { length: count },
        (_, i) => `${month}-${String(i + 1).padStart(2, '0')}`
    );
}

/**
 * ค่าเฉลี่ยราคาดีเซลของเดือนที่กำหนด
 *
 * @param byDate ประวัติ %สะสม — key คือ "วันแรกที่ราคานั้นมีผล" ไม่ใช่ทุกวัน
 * @param month  เดือนที่ต้องการ รูปแบบ YYYY-MM
 * @param today  วันนี้ (ISO) ใช้ตัดสินว่าเดือนจบหรือยัง — ไม่ส่ง = ไม่ตรวจข้อนี้
 *
 * ราคาของแต่ละวันคือของงวดล่าสุดที่เริ่มไม่เกินวันนั้น จึงต้องกางเป็นรายวันก่อน
 * ค่อยเฉลี่ย · ถ้าเฉลี่ยจากค่าในตารางตรง ๆ จะกลายเป็นเฉลี่ยตามจำนวนงวด
 * ซึ่งให้น้ำหนักงวดที่ใช้วันเดียวเท่ากับงวดที่ใช้ทั้งเดือน — ผิดมหันต์
 */
export function monthlyAverageDiesel(
    byDate: OilBands | null | undefined,
    month: string,
    today?: string
): MonthlyAverage {
    if (!validMonth(month)) return { ...EMPTY, month };

    /*
      รับเฉพาะวันที่ที่เป็นวันจริง และค่าที่เป็นตัวเลขใช้ได้จริง

      ข้อมูลมาจาก RTDB ซึ่งเก็บคีย์ที่ถูกลบเป็น null · ถ้าปล่อยผ่าน null จะกลาย
      เป็น 0 แล้วราคาเหลือแค่ OIL_BASE (31.94) เงียบ ๆ ทั้งที่จริงคือ 40 บาท
      ส่วน NaN/undefined ทำให้ค่าเฉลี่ยเป็น NaN แต่ usable ยังเป็น true
      ผู้เรียกที่เขียน if (r.usable) ตามปกติจะคิดเงินจาก NaN ไปเลย

      ไฟล์นี้ยึดหลักเดียวกับที่อื่นในระบบ: ข้อมูลไม่ครบให้บอกว่าใช้ไม่ได้
      ดีกว่าคืนตัวเลขที่ดูน่าเชื่อแต่ผิด
    */
    const isDay = (d: string): boolean => {
        if (!/^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/.test(d)) return false;
        // กันวันที่ที่รูปแบบถูกแต่ไม่มีจริง เช่น 2026-02-31
        const [y, m, dd] = d.split('-').map(Number);
        return new Date(Date.UTC(y, m - 1, dd)).getUTCDate() === dd;
    };

    const src = byDate || {};
    const dates = Object.keys(src).filter(isDay).sort();
    if (!dates.length) return { ...EMPTY, month };

    const days = monthDaysOf(month);

    /*
      เดือนต้องจบก่อนถึงคำนวณได้ — ทาง ก. ที่ตกลงกันไว้

      ค่าเฉลี่ยของเดือนที่ยังไม่จบจะเปลี่ยนไปเรื่อย ๆ ทุกครั้งที่ราคาน้ำมันขยับ
      ถ้าเอาไปคิดเงินแล้ววางบิล พอสิ้นเดือนตัวเลขจะไม่ตรงกับที่วางไป
      ต้องตามแก้ยอดย้อนหลังซึ่งยุ่งกว่าการรอ

      ตัดส่วนเวลาทิ้งก่อนเทียบ เพราะผู้เรียกอาจส่ง new Date().toISOString()
      ซึ่งได้ "2026-08-31T10:30:00Z" · สตริงนั้นมากกว่า "2026-08-31" (T เรียงหลัง)
      ถ้าเทียบดิบ ๆ ด่านนี้จะหลุดพอดีในวันสุดท้ายของเดือน ซึ่งเป็นวันที่คนปิดยอด
      มีโอกาสกดมากที่สุด · oilPriceAtDate ก็ตัดด้วย dayOf ด้วยเหตุผลเดียวกัน

      เทียบกับวันสุดท้ายอย่างเดียวพอ ไม่ต้องตรวจว่าอยู่ในเดือนไหม —
      เดือนที่ยังไม่เริ่มก็ยังไม่จบเหมือนกัน (ขอเดือน ส.ค. ตั้งแต่เดือน มี.ค.
      ก็ต้องไม่ได้ค่า ไม่ใช่เอาราคาเดือน มี.ค. ไปยืดคลุมทั้งเดือน ส.ค.)
    */
    const todayDay = (today || '').split('T')[0];
    if (todayDay && todayDay <= days[days.length - 1]) {
        return { ...EMPTY, month, status: 'month-not-over' };
    }

    /*
      ข้อมูลต้องเริ่มก่อนเดือนนี้ ไม่งั้นวันต้น ๆ ของเดือนจะไม่มีราคา

      เฉลี่ยเท่าที่มีไม่ได้ เพราะตัวเลขจะดูสมเหตุสมผลแต่ผิด และไม่มีใครรู้ว่าผิด
      เช่นเดือนที่มีข้อมูลแค่ 7 วันท้าย ซึ่งบังเอิญน้ำมันแพงผิดปกติ
    */
    if (dates[0] > days[0]) {
        return { ...EMPTY, month, status: 'before-history' };
    }

    /*
      ตรวจค่าเสียเฉพาะงวดที่มีผลต่อเดือนนี้ ไม่ใช่ทั้งประวัติ

      ประวัติราคาเก็บยาวหลายปีและมาจาก RTDB ซึ่งเก็บคีย์ที่ถูกลบเป็น null
      ถ้าตรวจทั้งก้อน คีย์เสียเพียงตัวเดียวในปีก่อนจะทำให้ทุกเดือนคำนวณไม่ได้หมด
      ทั้งที่เดือนที่ขอมาไม่ได้ใช้ค่านั้นเลย

      งวดที่มีผลคือทุกงวดที่เริ่มไม่เกินวันสุดท้ายของเดือน (งวดก่อนหน้าถูกใช้
      เป็นราคาของวันต้นเดือนได้) ส่วนงวดหลังจากนั้นไม่มีทางถูกหยิบมาใช้
    */
    const lastDay = days[days.length - 1];
    const relevant = dates.filter(d => d <= lastDay);
    if (relevant.some(d => !Number.isFinite(src[d]))) {
        return { ...EMPTY, month, status: 'bad-data' };
    }

    // กางเป็นรายวัน — ราคาของวันหนึ่งคือของงวดล่าสุดที่เริ่มไม่เกินวันนั้น
    let idx = 0;
    let cur = byDate![dates[0]];
    let sum = 0;
    let min = Infinity;
    let max = -Infinity;

    for (const day of days) {
        while (idx + 1 < dates.length && dates[idx + 1] <= day) {
            idx++;
            cur = byDate![dates[idx]];
        }
        const diesel = OIL_BASE + cur;
        sum += diesel;
        if (diesel < min) min = diesel;
        if (diesel > max) max = diesel;
    }

    /*
      ปัด 3 ตำแหน่งแบบครึ่งขึ้นให้ได้จริง

      Math.round((sum / n) * 1000) ไม่พอ เพราะ sum สะสมความคลาดเคลื่อนจากการบวก
      ทศนิยมมาเรื่อย ๆ · ค่าที่ควรลงตัวพอดีที่ .0005 จะกลายเป็นน้อยกว่านิดเดียว
      แล้ว Math.round ปัดลง ได้ผลต่างจากที่หน่วยงานคำนวณด้วยมือ

      เกิดได้จริงในเดือน ก.พ. (28 วัน) เช่น 7 วัน 35.00 + 21 วัน 35.01
      = 35.0075 พอดี · ต้องได้ 35.008 ไม่ใช่ 35.007

      แก้ด้วยการหารในหน่วย 1/1000 บาทก่อน แล้วปัดจากเศษที่เป็นจำนวนเต็ม
      ซึ่งไม่มีความคลาดเคลื่อนให้สะสม
    */
    const totalMilli = Math.round(sum * 1000);
    const n = days.length;
    const whole = Math.floor(totalMilli / n);
    const rem = totalMilli - whole * n;
    // เศษ >= ครึ่งหนึ่งของตัวหาร ให้ปัดขึ้น (เทียบด้วยจำนวนเต็ม ไม่มี .5 ให้พลาด)
    const diesel = (whole + (rem * 2 >= n ? 1 : 0)) / 1000;

    return {
        diesel,
        month,
        days: days.length,
        min: Math.round(min * 1000) / 1000,
        max: Math.round(max * 1000) / 1000,
        status: 'exact',
        usable: true,
    };
}
