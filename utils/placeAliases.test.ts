import { describe, it, expect } from 'vitest';
import { canonicalPlace, samePlace } from './placeAliases';

/*
  ทะเบียนชื่อสถานที่ — แก้ปัญหาชื่อในใบงานกับในตารางเรทเขียนคนละแบบ

  ตรวจเมื่อ 2 ต.ค. 2569: ใบงาน 145 ชื่อ · ตารางเรท 138 ชื่อ · ตรงกันแค่ 14
  ทำให้ไม่มีใครใช้ฟีเจอร์เรทตามราคาน้ำมันได้เลย (0 จาก 3,013 ใบ)

  หลักสำคัญ: ห้ามจับคู่แบบ "คล้ายกัน" — ถ้าจับผิดจะคิดเงินด้วยเรทของเส้นทางอื่น
  ยอมให้ "ไม่พบเรท" ดีกว่าจับคู่ผิดเงียบ ๆ
*/

describe('canonicalPlace — ชื่อมาตรฐาน', () => {
    it('แปลงชื่อที่อยู่ในทะเบียน', () => {
        expect(canonicalPlace('สหพัฒน์ศรีราชา')).toBe('สหพัฒน์ ศรีราชา');
        expect(canonicalPlace('มาม่า ลำพูน')).toBe('มาม่าลำพูน');
        expect(canonicalPlace('ล่ำสูง(บางปู)')).toBe('ล่ำสูง บางปู');
    });

    it('คืนชื่อเดิมถ้าไม่รู้จัก — ไม่เดา', () => {
        expect(canonicalPlace('สถานที่ที่ไม่มีในทะเบียน')).toBe('สถานที่ที่ไม่มีในทะเบียน');
    });

    it('ตัดช่องว่างหัวท้าย และรับค่าว่างได้', () => {
        expect(canonicalPlace('  มาม่า ลำพูน  ')).toBe('มาม่าลำพูน');
        expect(canonicalPlace('')).toBe('');
        expect(canonicalPlace(undefined as unknown as string)).toBe('');
    });
});

describe('samePlace — ที่เดียวกันไหม', () => {
    it('ชื่อตรงเป๊ะ', () => {
        expect(samePlace('มาม่าลำพูน', 'มาม่าลำพูน')).toBe(true);
    });

    it('ชื่อที่อยู่ในทะเบียน', () => {
        expect(samePlace('สหพัฒน์ศรีราชา', 'สหพัฒน์ ศรีราชา')).toBe(true);
        expect(samePlace('ล่ำสูง(บางปู)', 'ล่ำสูง บางปู')).toBe(true);
    });

    it('ต่างกันแค่ช่องว่างหรือวงเล็บ ถือว่าที่เดียวกัน', () => {
        /*
          พิสูจน์ได้ด้วยตัวอักษร ไม่ต้องให้คนยืนยัน
          ต่างจากชื่อที่เรียกคนละอย่าง ซึ่งต้องใส่ในทะเบียนเท่านั้น
        */
        expect(samePlace('กทม ปริมณฑล', 'กทม  ปริมณฑล')).toBe(true);
        expect(samePlace('อาหารสากล (นครปฐม)', 'อาหารสากล นครปฐม')).toBe(true);
        expect(samePlace('คลอง13 / กทม', 'คลอง13 กทม')).toBe(true);
    });

    /*
      ข้อสำคัญที่สุด: ห้ามจับคู่ชื่อที่แค่ "คล้าย" กัน

      ในข้อมูลจริงมีชื่อแบบนี้เยอะมาก เช่น "นีโอสยาม เชียงใหม่" กับ "เชียงใหม่"
      ซึ่งอาจเป็นคนละที่ · ถ้าจับคู่ให้ จะคิดค่าขนส่งด้วยเรทของเส้นทางอื่น
    */
    it('ชื่อที่แค่คล้ายกัน ต้องไม่ถือว่าที่เดียวกัน', () => {
        expect(samePlace('นีโอสยาม เชียงใหม่', 'เชียงใหม่')).toBe(false);
        expect(samePlace('ศูนย์กระจายสินค้า เซเว่น ปทุมธานี', 'ปทุมธานี')).toBe(false);
        expect(samePlace('แดรี่โด อินเตอร์ฟู้ดส์-ลาดกระบัง', 'ซันลี บางปะกง')).toBe(false);
        expect(samePlace('7-11 มหาชัย', 'ศูนย์กระจาย ซีพีออลล์ มหาชัย')).toBe(false);
    });

    it('ชื่อว่างต้องไม่ตรงกับอะไรเลย แม้แต่ชื่อว่างด้วยกัน', () => {
        // ถ้าคืน true ใบงานที่ไม่มีต้นทางจะจับคู่กับแถวเรทที่ไม่มีต้นทางได้
        expect(samePlace('', '')).toBe(false);
        expect(samePlace('', 'มาม่าลำพูน')).toBe(false);
        expect(samePlace('มาม่าลำพูน', '')).toBe(false);
    });

    it('เทียบสองทางได้ผลเหมือนกัน', () => {
        expect(samePlace('สหพัฒน์ศรีราชา', 'สหพัฒน์ ศรีราชา')).toBe(true);
        expect(samePlace('สหพัฒน์ ศรีราชา', 'สหพัฒน์ศรีราชา')).toBe(true);
    });
});

describe('ชื่อที่ผู้ใช้ยืนยันว่าเป็นที่เดียวกัน', () => {
    it('แดรี่โด อินเตอร์ฟู้ดส์-ลาดกระบัง = แดรี่โด ลาดกระบัง (3 ต.ค. 2569)', () => {
        expect(samePlace('แดรี่โด อินเตอร์ฟู้ดส์-ลาดกระบัง', 'แดรี่โด ลาดกระบัง')).toBe(true);
        expect(samePlace('แดรี่โด ลาดกระบัง', 'แดรี่โด อินเตอร์ฟู้ดส์-ลาดกระบัง')).toBe(true);
    });

    it('เซเว่น ร่มเกล้า = ซีพีออลล์ สุวรรณภูมิ (3 ต.ค. 2569)', () => {
        expect(samePlace('ศูนย์กระจายสินค้า เซเว่น ร่มเกล้า', 'ศูนย์กระจาย ซีพีออลล์ สุวรรณภูมิ')).toBe(true);
    });

    it('แม็คโคร นครปฐม = แม็คโครเมืองนครปฐม (3 ต.ค. 2569)', () => {
        expect(samePlace('แม็คโคร นครปฐม', 'แม็คโครเมืองนครปฐม')).toBe(true);
    });

    it('อาหารสากล-ดอนยายหอม = อาหารสากล (นครปฐม) (3 ต.ค. 2569)', () => {
        expect(samePlace('อาหารสากล-ดอนยายหอม นครปฐม', 'อาหารสากล (นครปฐม)')).toBe(true);
    });

    it('ยืนยันแค่ต้นทาง ไม่ได้ทำให้ปลายทางของเส้นนั้นตรงไปด้วย', () => {
        // ปลายทาง "เซเว่น มหาชัย" กับ "ซีพีออลล์ มหาชัย" ยังไม่ได้ยืนยัน
        expect(samePlace('ศูนย์กระจายสินค้า เซเว่น มหาชัย', 'ศูนย์กระจาย ซีพีออลล์ มหาชัย')).toBe(false);
    });
});
