/**
 * ต้นทางในตารางที่หมายถึง "ต้นทางไหนก็ได้"
 *
 * ตารางโอเคนะ แม่สอด แถว 160-162 เขียนต้นทางว่า "งานย่อย" · ราคากลางของโอเคนะ
 * มีต้นทาง 15 แบบ (เพนส์, นีโอสยาม สาย3, นมไทย ฯลฯ) ที่ราคาตรงกับแถวนี้
 * จึงตีความว่า "รับของย่อยจากต้นทางไหนก็ได้ ไปแม่สอด" — ผู้ใช้อนุมัติ 3 ต.ค. 2569
 * และส่งให้หน่วยงานยืนยันอีกครั้ง
 */
const ANY_ORIGIN = new Set(['งานย่อย']);

/**
 * ต้นทางที่ตารางเขียนผิด (ต้นทาง = ปลายทาง) แยกตามผู้รับเหมา
 *
 * ตารางพรมณี 24h แถว 108-119 เขียนต้นทางซ้ำกับปลายทางทุกแถว ในไฟล์ต้นฉบับ
 * ก็เป็นแบบนั้น · ราคากลางของพรมณีทั้ง 26 เส้นมีต้นทางเดียวคือสหพัฒน์ศรีราชา
 * — ผู้ใช้อนุมัติ 3 ต.ค. 2569 และส่งให้หน่วยงานยืนยันอีกครั้ง
 *
 * ไม่แก้ข้อมูลในตาราง เพราะเรทต้องคัดลอกตามไฟล์ของหน่วยงานตรง ๆ
 * แก้แค่ตอนจับคู่ — ถ้าหน่วยงานส่งไฟล์ที่แก้แล้วมา แถวจะไม่เข้าเงื่อนไขนี้เอง
 */
const ORIGIN_WHEN_SAME_AS_DEST: Record<string, string> = {
    'พรมณี 24เอช ทรานสปอร์ต': 'สหพัฒน์ศรีราชา',
};

/** สถานที่นี้อยู่ในเขตที่ตารางเรียกว่า zone ไหม */
export function inZone(zone: string, place: string): boolean {
    const p = (place || '').trim();
    if (!p) return false;
    for (const [name, members] of Object.entries(ZONE_MEMBERS)) {
        if (!samePlace(name, zone)) continue;
        if (members.some(m => samePlace(m, p))) return true;
    }
    return false;
}

/**
 * จับคู่ได้แบบไหน
 *   exact    — ชื่อตรง (ผ่านทะเบียนชื่อ)
 *   inferred — ตามเขต / ต้นทางไหนก็ได้ / ต้นทางที่ตารางเขียนผิด
 * แยกไว้ให้ผู้เรียกเลือกแถวที่ชื่อตรงก่อนเสมอ และแสดงให้คนทำบิลเห็นว่าจับคู่จากอะไร
 */
export type RouteMatch = 'exact' | 'inferred' | null;

const matchPlace = (ratePlace: string, jobPlace: string): RouteMatch => {
    if (samePlace(ratePlace, jobPlace)) return 'exact';
    if (inZone(ratePlace, jobPlace)) return 'inferred';
    return null;
};

/** ต้นทางที่ใช้จับคู่ของแถวนี้ — ปกติคือต้นทางในตาราง ยกเว้นแถวที่ตารางเขียนผิด */
export function rowOrigin(row: FuelRateRow): { origin: string; fixed: boolean } {
    const o = (row.origin || '').trim();
    const d = (row.destination || '').trim();
    const fix = ORIGIN_WHEN_SAME_AS_DEST[canonicalSubcontractor(row.company || '')];
    if (fix && o && o === d) return { origin: fix, fixed: true };
    return { origin: row.origin, fixed: false };
}

/** เส้นทางของใบงานตรงกับแถวเรทนี้ไหม (ไม่ดูผู้รับเหมาและประเภทรถ) */
export function matchRoute(row: FuelRateRow, origin: string, destination: string): RouteMatch {
    if (!(origin || '').trim() || !(destination || '').trim()) return null;

    const ro = rowOrigin(row);
    const o: RouteMatch = ANY_ORIGIN.has((ro.origin || '').trim())
        ? 'inferred'
        : matchPlace(ro.origin, origin);
    if (!o) return null;

    const d = matchPlace(row.destination, destination);
    if (!d) return null;

    return o === 'exact' && d === 'exact' && !ro.fixed ? 'exact' : 'inferred';
}
