/**
 * ชื่อสถานที่ที่สะกดต่างกันแต่เป็นที่เดียวกัน
 *
 * ปัญหาที่ไฟล์นี้แก้: ชื่อสถานที่ในใบงานกับในตารางเรทของหน่วยงานเขียนคนละแบบ
 * ตรวจเมื่อ 2 ต.ค. 2569 — ใบงาน 3 เดือนล่าสุดมีชื่อสถานที่ 145 ชื่อ
 * ตารางเรทมี 138 ชื่อ แต่ **ตรงกันพอดีแค่ 14 ชื่อ**
 * ผลคือเลือกเรทจากตารางแล้วไม่เจอเส้นทางของตัวเอง — ทั้งระบบจึงไม่มีใครใช้
 * ฟีเจอร์เรทตามราคาน้ำมันเลยสักใบ (0 จาก 3,013 ใบ)
 *
 * ไฟล์นี้เป็น "ที่เดียว" ที่บอกว่าชื่อไหนคือที่เดียวกัน ใช้ตอนจับคู่ใบงาน
 * กับตารางเรท · เพิ่มชื่อใหม่ที่นี่ที่เดียว อย่ากระจายการแปลงชื่อไปตามหน้าจอ
 *
 * **ห้ามเดา** — ใส่เฉพาะคู่ที่ยืนยันแล้วว่าเป็นที่เดียวกันจริง
 * ถ้าจับคู่ผิด ค่าขนส่งจะถูกคิดด้วยเรทของเส้นทางอื่น ซึ่งผิดเรื่องเงิน
 * คู่ที่ยังไม่ยืนยันให้ปล่อยไว้ ระบบจะบอกว่า "ไม่พบเรท" ซึ่งปลอดภัยกว่า
 */

/** ชื่อที่สะกดต่าง -> ชื่อมาตรฐานที่ใช้ในตารางเรท */
const ALIASES: Record<string, string> = {
    /*
      กลุ่มที่ต่างกันแค่ช่องว่างหรือวงเล็บ — เทียบแล้วตัวอักษรตรงกันทุกตัว
      จึงยืนยันได้โดยไม่ต้องถามใคร (ตรวจ 2 ต.ค. 2569)
    */
    'สหพัฒน์ศรีราชา': 'สหพัฒน์ ศรีราชา',
    'มาม่า ลำพูน': 'มาม่าลำพูน',
    'ล่ำสูง(บางปู)': 'ล่ำสูง บางปู',
    'แม็คโคร ศาลายา': 'แม็คโครศาลายา',
    'แม็คโคร ศาลายา+นีโอสยาม สาย3': 'แม็คโครศาลายา+นีโอสยามสาย3',
};

/**
 * ตัดช่องว่าง วงเล็บ และเครื่องหมายออก เพื่อเทียบชื่อที่ต่างกันแค่การเว้นวรรค
 *
 * ทำแยกจากตาราง ALIASES เพราะกรณีแบบนี้มีเรื่อย ๆ และเป็นการเทียบที่
 * "พิสูจน์ได้ด้วยตัวอักษร" ไม่ต้องให้คนยืนยัน ต่างจากชื่อที่เรียกคนละอย่าง
 * เช่น "แดรี่โด อินเตอร์ฟู้ดส์" กับ "ซันลี บางปะกง" ซึ่งต้องใส่ใน ALIASES เท่านั้น
 */
const squash = (s: string): string =>
    (s || '').toLowerCase().replace(/[\s()/.\-,]/g, '');

/** ชื่อมาตรฐานของสถานที่ — คืนชื่อเดิมถ้าไม่รู้จัก */
export function canonicalPlace(name: string): string {
    const raw = (name || '').trim();
    if (!raw) return '';
    return ALIASES[raw] ?? raw;
}

/**
 * ชื่อสองชื่อนี้เป็นที่เดียวกันไหม
 *
 * เทียบ 3 ชั้น: ตรงเป๊ะ → ผ่านทะเบียนชื่อ → ตัดช่องว่างแล้วตรงกัน
 * ไม่เทียบแบบ "คล้ายกัน" เพราะเสี่ยงจับคู่ผิดแล้วคิดเงินด้วยเรทของเส้นทางอื่น
 */
export function samePlace(a: string, b: string): boolean {
    const ca = canonicalPlace(a);
    const cb = canonicalPlace(b);
    if (!ca || !cb) return false;
    if (ca === cb) return true;
    return squash(ca) === squash(cb);
}
