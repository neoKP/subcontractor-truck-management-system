/**
 * ตัดช่องว่าง วงเล็บ และเครื่องหมายออก เพื่อเทียบชื่อที่ต่างกันแค่การเว้นวรรค
 *
 * ทำแยกจากตาราง ALIASES เพราะกรณีแบบนี้มีเรื่อย ๆ และเป็นการเทียบที่
 * "พิสูจน์ได้ด้วยตัวอักษร" ไม่ต้องให้คนยืนยัน ต่างจากชื่อที่เรียกคนละอย่าง
 * เช่น "แดรี่โด อินเตอร์ฟู้ดส์" กับ "ซันลี บางปะกง" ซึ่งต้องใส่ใน ALIASES เท่านั้น
 */
const squash = (s: string): string =>
    (s || '').toLowerCase().replace(/[\s()/.\-,]/g, '');

/** ชื่อมาตรฐานของสถานที่ — คืนชื่อเดิมถ้าไม่รู้จัก */
export function canonicalPlace(name: string): string {
    const raw = (name || '').trim();
    if (!raw) return '';
    return ALIASES[raw] ?? raw;
}

/**
 * ชื่อสองชื่อนี้เป็นที่เดียวกันไหม
 *
 * เทียบ 3 ชั้น: ตรงเป๊ะ → ผ่านทะเบียนชื่อ → ตัดช่องว่างแล้วตรงกัน
 * ไม่เทียบแบบ "คล้ายกัน" เพราะเสี่ยงจับคู่ผิดแล้วคิดเงินด้วยเรทของเส้นทางอื่น
 */
export function samePlace(a: string, b: string): boolean {
    const ca = canonicalPlace(a);
    const cb = canonicalPlace(b);
    if (!ca || !cb) return false;
    if (ca === cb) return true;
    return squash(ca) === squash(cb);
}
